CREATE TABLE IF NOT EXISTS whellco_medical_duties (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    character_id INT UNSIGNED NOT NULL,
    job_id VARCHAR(64) NOT NULL,
    on_duty TINYINT(1) NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_whellco_medical_duties (character_id, job_id)
);

CREATE TABLE IF NOT EXISTS whellco_medical_injuries (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    character_id INT UNSIGNED NOT NULL,
    injury_type VARCHAR(64) NOT NULL,
    severity VARCHAR(32) NOT NULL,
    healed TINYINT(1) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    healed_at TIMESTAMP NULL DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS whellco_medical_treatments (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    medic_id INT UNSIGNED NOT NULL,
    patient_id INT UNSIGNED NOT NULL,
    injury_type VARCHAR(64) NOT NULL,
    treatment VARCHAR(255) NOT NULL,
    treated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
