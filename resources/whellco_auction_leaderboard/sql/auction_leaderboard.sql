CREATE TABLE IF NOT EXISTS whellco_auction_leaderboard (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    player_id VARCHAR(64) NOT NULL,
    total_bids INT UNSIGNED NOT NULL DEFAULT 0,
    total_spent INT UNSIGNED NOT NULL DEFAULT 0,
    auctions_won INT UNSIGNED NOT NULL DEFAULT 0,
    auctions_sold INT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY player_leaderboard (player_id)
);
