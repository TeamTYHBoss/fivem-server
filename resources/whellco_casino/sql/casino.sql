CREATE TABLE IF NOT EXISTS whellco_casino_memberships (
    character_id INT UNSIGNED NOT NULL PRIMARY KEY,
    tier VARCHAR(16) NOT NULL DEFAULT 'free',
    purchased_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS whellco_casino_penthouses (
    character_id INT UNSIGNED NOT NULL PRIMARY KEY,
    lighting VARCHAR(24) NOT NULL DEFAULT 'standard',
    flooring VARCHAR(24) NOT NULL DEFAULT 'standard',
    furniture VARCHAR(24) NOT NULL DEFAULT 'standard',
    security VARCHAR(24) NOT NULL DEFAULT 'standard',
    purchased_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS whellco_casino_garage_spaces (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    character_id INT UNSIGNED NOT NULL,
    space_type VARCHAR(16) NOT NULL,
    purchased_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY character_space (character_id, space_type)
);

CREATE TABLE IF NOT EXISTS whellco_casino_game_history (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    character_id INT UNSIGNED NOT NULL,
    game VARCHAR(16) NOT NULL,
    bet INT UNSIGNED NOT NULL DEFAULT 0,
    payout INT NOT NULL DEFAULT 0,
    result VARCHAR(64) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS whellco_casino_transactions (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    character_id INT UNSIGNED NOT NULL,
    type VARCHAR(24) NOT NULL,
    amount INT NOT NULL,
    description VARCHAR(128) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
