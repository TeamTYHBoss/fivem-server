CREATE TABLE IF NOT EXISTS whellco_collisions (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    vehicle_id INT UNSIGNED NOT NULL,
    owner_id VARCHAR(64) NOT NULL,
    collision_type VARCHAR(32) NOT NULL,
    damage INT UNSIGNED NOT NULL DEFAULT 0,
    repair_cost INT UNSIGNED NOT NULL DEFAULT 0,
    repaired TINYINT(1) NOT NULL DEFAULT 0,
    repaired_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
