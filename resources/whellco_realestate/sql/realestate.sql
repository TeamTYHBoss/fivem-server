CREATE TABLE IF NOT EXISTS whellco_properties (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL UNIQUE,
    label VARCHAR(128) NOT NULL,
    price INT NOT NULL,
    rent INT NOT NULL,
    owner_id INT UNSIGNED NULL,
    is_rented TINYINT(1) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS whellco_property_purchases (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    buyer_id INT UNSIGNED NOT NULL,
    price INT NOT NULL,
    purchased_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS whellco_property_rentals (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    tenant_id INT UNSIGNED NOT NULL,
    rent INT NOT NULL,
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMP NULL DEFAULT NULL
);
