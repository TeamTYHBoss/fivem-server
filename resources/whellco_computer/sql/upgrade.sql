CREATE TABLE IF NOT EXISTS whellco_computer_state (
 citizenid VARCHAR(50) NOT NULL PRIMARY KEY,
 state LONGTEXT NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS whellco_computer_posts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 citizenid VARCHAR(50) NOT NULL,
 author VARCHAR(150) NOT NULL,
 content VARCHAR(500) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS whellco_computer_comments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 post_id BIGINT UNSIGNED NOT NULL,
 citizenid VARCHAR(50) NOT NULL,
 author VARCHAR(150) NOT NULL,
 content VARCHAR(300) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX (post_id, id),
 FOREIGN KEY (post_id) REFERENCES whellco_computer_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS whellco_computer_messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 sender VARCHAR(50) NOT NULL,
 recipient VARCHAR(50) NOT NULL,
 content VARCHAR(1000) NOT NULL,
 read_at TIMESTAMP NULL DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX (recipient, id),
 INDEX (sender, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS whellco_computer_notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 citizenid VARCHAR(50) NOT NULL,
 kind VARCHAR(32) NOT NULL,
 reference_id BIGINT UNSIGNED NULL,
 content VARCHAR(300) NOT NULL,
 read_at TIMESTAMP NULL DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX (citizenid, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS whellco_computer_listings (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 seller VARCHAR(50) NOT NULL,
 item VARCHAR(100) NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 metadata LONGTEXT NOT NULL,
 price BIGINT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 buyer VARCHAR(50) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX (status, id),
 INDEX (seller, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS whellco_computer_transfers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 request_id VARCHAR(64) NOT NULL UNIQUE,
 sender VARCHAR(50) NOT NULL,
 recipient VARCHAR(50) NOT NULL,
 amount BIGINT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX (sender, id),
 INDEX (recipient, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
