CREATE TABLE IF NOT EXISTS whellco_auction_stats (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    auction_id INT UNSIGNED NOT NULL,
    plate VARCHAR(8) NOT NULL,
    total_bids INT UNSIGNED NOT NULL DEFAULT 0,
    highest_bid INT UNSIGNED NOT NULL DEFAULT 0,
    final_bid INT UNSIGNED NOT NULL DEFAULT 0,
    winner_id VARCHAR(64) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY auction_stats (auction_id)
);
