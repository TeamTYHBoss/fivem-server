CREATE TABLE IF NOT EXISTS whellco_plate_auctions (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    plate VARCHAR(8) NOT NULL,
    seller_id VARCHAR(64) NOT NULL,
    starting_bid INT UNSIGNED NOT NULL DEFAULT 500,
    current_bid INT UNSIGNED NOT NULL DEFAULT 0,
    current_bidder_id VARCHAR(64) NULL,
    ends_at DATETIME NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS whellco_plate_bids (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    auction_id INT UNSIGNED NOT NULL,
    bidder_id VARCHAR(64) NOT NULL,
    bid_amount INT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
