CREATE TABLE IF NOT EXISTS whellco_police_duties (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    character_id INT UNSIGNED NOT NULL,
    job_id VARCHAR(64) NOT NULL,
    on_duty TINYINT(1) NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_whellco_police_duties (character_id, job_id)
);

CREATE TABLE IF NOT EXISTS whellco_police_citations (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    officer_id INT UNSIGNED NOT NULL,
    target_id INT UNSIGNED NOT NULL,
    citation_type VARCHAR(64) NOT NULL,
    fine INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS whellco_police_arrests (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    officer_id INT UNSIGNED NOT NULL,
    target_id INT UNSIGNED NOT NULL,
    reason VARCHAR(255) NOT NULL,
    arrested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at TIMESTAMP NULL DEFAULT NULL
);
