CREATE TABLE IF NOT EXISTS whellco_vehicle_tuning (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    plate VARCHAR(8) NOT NULL,
    category VARCHAR(32) NOT NULL,
    level INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY tuning_unique (plate, category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS whellco_vehicle_handling (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    plate VARCHAR(8) NOT NULL,
    handling_profile VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY handling_unique (plate)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;